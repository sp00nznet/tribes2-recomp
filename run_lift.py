#!/usr/bin/env python3
"""Lift Tribes2.exe (work/t2.functions.json) to C in src/recomp/gen/.

One module: Tribes2.exe 25034 (base 0x00400000), lifted whole; its DLLs
(Miles mss32, Immersion IFC22) and opengl32 load natively. The loop is pcrecomp's shared
`tools/lift/drive32.py`; this file only names the inputs and writes the
dispatch table.

    py -3 tools/catalog.py     # first: RTTI seeds + the function catalog
    py -3 run_lift.py
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
# PCRECOMP picks another toolkit checkout, the same knob CMakeLists.txt has:
# the lifter and the runtime header must come from the same tree.
TOOLS = os.path.join(os.environ.get('PCRECOMP', os.path.join(HERE, '..', 'pcrecomp')), 'tools')
sys.path[:0] = [os.path.join(TOOLS, 'lift'), os.path.join(TOOLS, 'pe')]
from drive32 import lift_image  # noqa: E402

WORK = os.path.join(HERE, 'work')
OUT = os.path.join(HERE, 'src', 'recomp', 'gen')


def put(path, text):
    """Write only a change, so an unchanged header does not rebuild every chunk."""
    if not os.path.exists(path) or open(path, newline='').read() != text:
        with open(path, 'w', newline='\n') as f:
            f.write(text)


def main():
    t0 = time.time()
    cat = os.path.join(WORK, 't2.functions.json')
    if not os.path.exists(cat):
        sys.exit('no catalog -- run `py -3 tools/catalog.py` first (README, Step by step)')
    seeds_p = os.path.join(WORK, 't2.seeds.json')
    seeds = [e['address'] for e in json.load(open(seeds_p))] if os.path.exists(seeds_p) else []
    os.makedirs(OUT, exist_ok=True)
    st, entries = lift_image(os.path.join(HERE, 'game', 'Tribes2.exe'), cat, os.path.join(OUT, 't2'), seeds=seeds)
    json.dump(st, open(os.path.join(WORK, 'lift_stats.json'), 'w'), indent=1)
    put(os.path.join(OUT, 'recomp_funcs.h'),
        '/* AUTO-GENERATED by run_lift.py */\n#pragma once\n#include <stdint.h>\n\n'
        + ''.join('void sub_%08X(void);\n' % a for a in entries))
    put(os.path.join(OUT, 'recomp_dispatch.c'),
        '/* AUTO-GENERATED by run_lift.py */\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n\n'
        'const recomp_dispatch_entry_t recomp_dispatch_table[] = {\n'
        + ''.join('    { 0x%08Xu, sub_%08X },\n' % (a, a) for a in entries)
        + '};\nconst uint32_t recomp_dispatch_count = %d;\n' % len(entries))
    print('=' * 60)
    print('  %d functions in the dispatch table, lift errors %d, unimplemented instructions %d, %.0fs'
          % (len(entries), st['errors'], sum(st['unimplemented'].values()), time.time() - t0))
    print('=' * 60)


if __name__ == '__main__':
    main()
